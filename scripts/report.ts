const OUT = 'ANOMALIES.md'

async function rows<T extends Record<string, unknown>>(
  sql: string,
  params: unknown[] = []
): Promise<T[]> {
  const res = await pool.query(sql, params)
  return res.rows as T[]
}

/** Отрисовывает массив объектов markdown-таблицей. */
function table(data: Record<string, unknown>[], columns?: string[]): string {
  if (data.length === 0) return '_(пусто)_\n'

  const cols = columns ?? Object.keys(data[0])
  const head = `| ${cols.join(' | ')} |`
  const sep = `| ${cols.map(() => '---').join(' | ')} |`
  const body = data
    .map(
      (r) =>
        `| ${cols
          .map((c) => {
            const v = r[c]
            if (v === null || v === undefined) return '—'
            // Экранируем вертикальную черту, иначе таблица развалится.
            return String(v).replace(/\|/g, '\\|')
          })
          .join(' | ')} |`
    )
    .join('\n')

  return `${head}\n${sep}\n${body}\n`
}

